/// Every tray `settings` define with its criteria, in [`Tray::all`] order.
///
/// # Errors
///
/// Returns [`Error::Config`] for a tray with neither built-in nor configured
/// criteria.
pub fn tray_criteria(settings: &ClassifyConfig) -> Result<Vec<(Tray, String)>> {
    Tray::all(settings)
        .into_iter()
        .map(|tray| {
            let text = settings
                .criteria
                .get(tray.as_str())
                .map(String::as_str)
                .or_else(|| {
                    BUILTIN_CRITERIA
                        .iter()
                        .find(|(k, _)| *k == tray.as_str())
                        .map(|(_, v)| *v)
                })
                .filter(|t| !t.trim().is_empty())
                .ok_or_else(|| {
                    Error::Config(format!(
                        "tray {tray} needs a description under [classify.criteria]"
                    ))
                })?
                .to_string();

            Ok((tray, text))
        })
        .collect()
}

/// The questions asked of every email: jevmail's three, the tray choice over
/// `trays` and urgency covering actions as well as replies, plus
/// `action_required`.
fn questions(trays: &[(Tray, String)]) -> Value {
    let criteria: serde_json::Map<String, Value> = trays
        .iter()
        .map(|(t, text)| (t.as_str().to_string(), Value::from(text.as_str())))
        .collect();

    json!({
        "category": {
            "type": "choice",
            "instructions": "Which tray does this email belong in? Judge from the sender, subject, headers, and body together.",
            "criteria": criteria,
        },
        "urgency": {
            "type": "score",
            "instructions": "How urgently does the recipient need to reply to or act on this email? Pick the level that best matches.",
            "criteria": [
                "No reply or action needed, or no time pressure at all",
                "Within a week is fine",
                "Within a few days is expected",
                "Today is expected",
                "A person is blocked, or a deadline falls within 24 hours",
            ],
        },
        "is_personal": {
            "type": "noul",
            "instructions": "Was this email written by a human specifically to this recipient, rather than sent to a list or generated by a system?",
        },
        "action_required": {
            "type": "noul",
            "instructions": "Does the recipient need to do something because of this email: reply, pay, sign, confirm, renew, book, or fix an account problem? Reading it, filing it or ignoring it is not an action.",
        },
    })
}

/// One email's decided outcome.
#[derive(Clone, Debug, PartialEq)]
pub struct Classification {
    /// The tray Jev chose.
    pub tray: Tray,
    /// Probability of every tray key.
    pub probs: BTreeMap<String, f64>,
    /// 1 to 5.
    pub urgency: u8,
    /// Probability the email was written by a person to the recipient.
    pub personal: f64,
    /// Probability the recipient has to reply or act (pay, sign, confirm...).
    pub action: f64,
    /// True when the top two tray probabilities are closer than the margin.
    pub unsure: bool,
    /// Model name from the response.
    pub model: String,
    /// Input tokens billed.
    pub input_tokens: u64,
}

/// Something that classifies one email state block.
pub trait Classifier: Send + Sync {
    /// Classifies the state block built by [`super::state::state_block`].
    fn classify(&self, state: &str) -> impl Future<Output = Result<Classification>> + Send;
}

/// The `answers` object of a System One response; a `None` is an answer or
/// value Jev left out.
#[derive(Debug, Default, Deserialize)]
struct Answers {
    category: Option<CategoryAnswer>,
    urgency: Option<ScoreAnswer>,
    is_personal: Option<NoulAnswer>,
    action_required: Option<NoulAnswer>,
}

#[derive(Debug, Default, Deserialize)]
struct CategoryAnswer {
    #[serde(default)]
    choice: String,
    #[serde(default)]
    probabilities: BTreeMap<String, f64>,
}

#[derive(Debug, Default, Deserialize)]
struct ScoreAnswer {
    score: Option<f64>,
}

#[derive(Debug, Default, Deserialize)]
struct NoulAnswer {
    noul: Option<f64>,
}

/// The System One response body.
#[derive(Debug, Default, Deserialize)]
struct Response {
    #[serde(default)]
    model: String,
    #[serde(default)]
    answers: Answers,
    #[serde(default)]
    usage: Usage,
}

#[derive(Debug, Default, Deserialize)]
struct Usage {
    #[serde(default)]
    input_tokens: u64,
}

/// Turns Jev's answers into a [`Classification`] over `trays`; model and
/// tokens are left for the caller.
fn decide(a: &Answers, margin: f64, trays: &[Tray]) -> Result<Classification> {
    let (Some(category), Some(urgency), Some(personal), Some(action)) =
        (&a.category, &a.urgency, &a.is_personal, &a.action_required)
    else {
        return Err(Error::Other("jev: missing answer".into()));
    };
    let (Some(score), Some(noul), Some(acts)) = (urgency.score, personal.noul, action.noul) else {
        return Err(Error::Other("jev: missing answer value".into()));
    };
    let tray = trays
        .iter()
        .find(|t| t.as_str() == category.choice)
        .cloned()
        // Static message: the choice is server-controlled text.
        .ok_or_else(|| Error::Other("jev: unknown choice".into()))?;
    let mut probs = BTreeMap::new();
    let (mut p1, mut p2) = (0.0_f64, 0.0_f64);

    for t in trays {
        let p = category
            .probabilities
            .get(t.as_str())
            .copied()
            .unwrap_or(0.0);

        probs.insert(t.as_str().to_string(), p);

        if p > p1 {
            (p1, p2) = (p, p1);
        } else if p > p2 {
            p2 = p;
        }
    }

    Ok(Classification {
        tray,
        probs,
        urgency: (score.round() as i64 + 1).clamp(1, 5) as u8,
        personal: noul,
        action: acts,
        unsure: p1 - p2 < margin - PROB_EPSILON,
        model: String::new(),
        input_tokens: 0,
    })
}

/// Client of `POST /v1/systemone`.
pub struct JevClient {
    http: reqwest::Client,
    base_url: String,
    /// Bearer key; never logged or included in errors.
    key: String,
    model: String,
    /// Top-two probability gap below which an answer is unsure.
    margin: f64,
    /// The trays Jev chooses from.
    trays: Vec<Tray>,
    /// The `questions` of every request, built from the trays.
    questions: Value,
    /// First retry wait when `Retry-After` is unusable; doubles each retry.
    backoff: Duration,
}

impl std::fmt::Debug for JevClient {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("JevClient")
            .field("base_url", &self.base_url)
            .field("model", &self.model)
            .finish_non_exhaustive()
    }
}

impl JevClient {
    /// A client for `base_url` (see [`JEV_BASE_URL`]) that sends `key` as a
    /// bearer token and takes the model, the unsure margin and the trays from
    /// `settings`.
    ///
    /// # Errors
    ///
    /// Returns [`Error::Config`] when a tray has no criteria ([`tray_criteria`]).
    pub fn new(base_url: &str, key: &str, settings: &ClassifyConfig) -> Result<JevClient> {
        let trays = tray_criteria(settings)?;

        Ok(JevClient {
            http: reqwest::Client::builder()
                .timeout(Duration::from_secs(30))
                .build()
                .unwrap_or_default(),
            base_url: base_url.trim_end_matches('/').to_string(),
            key: key.to_string(),
            model: settings.model.clone(),
            margin: settings.unsure_margin,
            questions: questions(&trays),
            trays: trays.into_iter().map(|(t, _)| t).collect(),
            backoff: Duration::from_secs(1),
        })
    }

    /// `text` without the key.
    fn scrub(&self, text: &str) -> String {
        if self.key.is_empty() {
            return text.to_string();
        }

        text.replace(&self.key, "<redacted>")
    }

    /// Sends the request once and returns status, `Retry-After` and body.
    async fn post(&self, payload: &Value) -> Result<(u16, Option<u64>, String)> {
        let resp = self
            .http
            .post(format!("{}/v1/systemone", self.base_url))
            .bearer_auth(&self.key)
            .json(payload)
            .send()
            .await
            .map_err(|e| Error::Http(self.scrub(&format!("jev: post: {}", e.without_url()))))?;
        let status = resp.status().as_u16();
        let retry_after = resp
            .headers()
            .get(reqwest::header::RETRY_AFTER)
            .and_then(|v| v.to_str().ok())
            .and_then(|v| v.trim().parse().ok());
        let body = resp.bytes().await.map_err(|e| {
            Error::Http(self.scrub(&format!("jev: read response: {}", e.without_url())))
        })?;

        // A response is never bigger than a classification; cap what is kept.
        let body = &body[..body.len().min(1 << 20)];

        Ok((
            status,
            retry_after,
            String::from_utf8_lossy(body).into_owned(),
        ))
    }
}

impl Classifier for JevClient {
    /// Asks Jev the questions about one state block, retrying 429 and
    /// 529 responses up to five requests in all.
    ///
    /// # Errors
    ///
    /// Returns [`Error::Http`] for transport failures and non-2xx answers
    /// (body cut to 200 characters, key removed) and [`Error::Other`] for an
    /// undecodable or incomplete answer.
    async fn classify(&self, state: &str) -> Result<Classification> {
        let payload = json!({ "state": state, "model": self.model, "questions": &self.questions });

        for attempt in 1.. {
            let (status, retry_after, body) = self.post(&payload).await?;

            if matches!(status, 429 | 529) && attempt < MAX_ATTEMPTS {
                let wait = retry_after
                    .map(Duration::from_secs)
                    .unwrap_or_else(|| self.backoff * 2u32.pow(attempt - 1));

                tokio::time::sleep(wait).await;

                continue;
            }

            if !(200..300).contains(&status) {
                let cut: String = body.chars().take(ERROR_BODY_CHARS).collect();

                return Err(Error::Http(
                    self.scrub(&format!("jev: status {status}: {cut}")),
                ));
            }

            // Static message: serde errors can quote the response.
            let resp: Response = serde_json::from_str(&body)
                .map_err(|_| Error::Other("jev: decode response".into()))?;
            let mut c = decide(&resp.answers, self.margin, &self.trays)
                .map_err(|e| Error::Other(self.scrub(&e.to_string())))?;

            c.model = resp.model;
            c.input_tokens = resp.usage.input_tokens;

            return Ok(c);
        }

        unreachable!("the loop returns on its last attempt")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The built-in description of `key`.
    fn builtin(key: &str) -> &'static str {
        BUILTIN_CRITERIA.iter().find(|(k, _)| *k == key).unwrap().1
    }

    /// The default trays.
    fn trays() -> Vec<Tray> {
        Tray::all(&ClassifyConfig::default())
    }

    #[test]
    fn criteria_come_from_the_config_then_the_built_ins() {
        let mut settings = ClassifyConfig::default();

        settings.trays.insert("bills".into(), "Bills".into());

        let err = tray_criteria(&settings).unwrap_err();

        assert!(
            err.to_string().contains("tray bills needs a description"),
            "{err}"
        );

        settings
            .criteria
            .insert("bills".into(), "Bills to pay.".into());
        settings
            .criteria
            .insert("social".into(), "Friends' chatter.".into());

        let criteria: BTreeMap<String, String> = tray_criteria(&settings)
            .unwrap()
            .into_iter()
            .map(|(t, text)| (t.to_string(), text))
            .collect();

        assert_eq!(criteria["bills"], "Bills to pay.");
        assert_eq!(criteria["social"], "Friends' chatter.");
        assert_eq!(criteria["spam"], builtin("spam"));
        assert_eq!(criteria.len(), settings.trays.len() + 1);
    }

    /// Answers with the given probabilities (missing trays absent), score and noul.
    fn answers(choice: &str, probs: &[(&str, f64)], score: f64) -> Answers {
        serde_json::from_value(json!({
            "category": {
                "choice": choice,
                "probabilities": probs.iter().cloned().collect::<BTreeMap<_, _>>(),
            },
            "urgency": { "score": score },
            "is_personal": { "noul": 0.8 },
            "action_required": { "noul": 0.3 },
        }))
        .unwrap()
    }

    fn unsure(probs: &[(&str, f64)], margin: f64) -> bool {
        decide(&answers("needs_reply", probs, 0.0), margin, &trays())
            .unwrap()
            .unsure
    }

    #[test]
    fn decide_matches_jevmail() {
        let sure = [("needs_reply", 0.57), ("receipts", 0.42)];

        // Gap exactly 0.15 in decimal is sure, just under is unsure.
        assert!(!unsure(&sure, 0.15));
        assert!(unsure(&[("needs_reply", 0.5), ("receipts", 0.4)], 0.15));
        assert!(!unsure(&[("needs_reply", 0.55), ("receipts", 0.40)], 0.15));
        assert!(unsure(&[("needs_reply", 0.5499), ("receipts", 0.40)], 0.15));
        assert!(unsure(&[("needs_reply", 0.5), ("receipts", 0.4)], 0.15));
        // A missing probability key counts as 0.
        assert!(!unsure(&[("needs_reply", 0.9)], 0.15));
        assert!(unsure(&[], 0.15));
        // A wider margin flips a 0.2 gap.
        let gap = [("needs_reply", 0.6), ("receipts", 0.4)];
        assert!(!unsure(&gap, 0.15));
        assert!(unsure(&gap, 0.3));

        // The server's choice stands even when it is not the most probable.
        let c = decide(
            &answers("social", &[("needs_reply", 0.9), ("social", 0.05)], 0.0),
            0.15,
            &trays(),
        )
        .unwrap();

        assert_eq!(c.tray, Tray::new("social"));
        assert_eq!(c.probs["needs_reply"], 0.9);
        assert_eq!(c.probs["spam"], 0.0);
        assert_eq!(c.probs.len(), 8);
        assert_eq!(c.personal, 0.8);
        assert_eq!(c.action, 0.3);

        // Urgency is round(score) + 1, halves away from zero, clamped to 1..=5.
        let urgency = |score| {
            decide(&answers("receipts", &[], score), 0.15, &trays())
                .unwrap()
                .urgency
        };

        assert_eq!(urgency(3.4), 4);
        assert_eq!(urgency(2.5), 4);
        assert_eq!(urgency(2.4), 3);
        assert_eq!(urgency(0.0), 1);
        assert_eq!(urgency(-3.0), 1);
        assert_eq!(urgency(9.0), 5);

        // Missing answers and unknown choices are errors.
        let missing: Answers = serde_json::from_value(json!({
            "category": { "choice": "receipts" },
            "urgency": { "score": 1.0 },
        }))
        .unwrap();
        let err = decide(&missing, 0.15, &trays()).unwrap_err();

        assert!(err.to_string().contains("jev: missing answer"), "{err}");

        let no_value: Answers = serde_json::from_value(json!({
            "category": { "choice": "receipts" },
            "urgency": {},
            "is_personal": { "noul": 0.1 },
            "action_required": { "noul": 0.1 },
        }))
        .unwrap();
        let err = decide(&no_value, 0.15, &trays()).unwrap_err();

        assert!(err.to_string().contains("missing answer value"), "{err}");

        let err = decide(&answers("newsletter", &[], 0.0), 0.15, &trays()).unwrap_err();

        assert!(err.to_string().contains("unknown choice"), "{err}");
    }

    #[test]
    fn questions_match_jevmail() {
        // Pieces copied from jevmail/internal/jev/questions.go, one per line;
        // urgency is reworded to cover actions.
        let category = concat!(
            "Which tray does this email belong in? Judge from ",
            "the sender, subject, headers, and body together.",
        );
        let needs_reply = concat!(
            "A real person expects a reply from the ",
            "recipient: a colleague, customer, friend, or existing ",
            "contact asking something or continuing a conversation.",
        );
        let updates = concat!(
            "Transactional or informational mail about the ",
            "recipient's own accounts and activity: bank and card ",
            "transaction alerts, OTPs and security notices, order, ",
            "delivery, and booking status, receipts and invoices, ",
            "bill reminders, service alarms, calendar or system ",
            "notifications. Automated, addressed to the recipient, ",
            "not trying to sell anything.",
        );
        let social = concat!(
            "Notifications generated by a social network, ",
            "forum, chat platform, or community site about activity ",
            "there: new followers, mentions, replies, direct ",
            "messages, group posts, friend requests, event RSVPs. ",
            "Sent by the platform, not written by a person to the ",
            "recipient.",
        );
        let spam = concat!(
            "Scams, phishing, fake invoices, or junk with no ",
            "legitimate purpose.",
        );
        let urgency = concat!(
            "How urgently does the recipient need to reply to ",
            "or act on this email? Pick the level that best matches.",
        );
        let personal = concat!(
            "Was this email written by a human specifically ",
            "to this recipient, rather than sent to a list or ",
            "generated by a system?",
        );
        let q = &questions(&tray_criteria(&ClassifyConfig::default()).unwrap());

        assert_eq!(q.as_object().unwrap().len(), 4);
        assert_eq!(q["category"]["type"], "choice");
        assert_eq!(q["category"]["instructions"], category);
        assert_eq!(q["category"]["criteria"]["needs_reply"], needs_reply);
        assert_eq!(q["category"]["criteria"]["social"], social);
        assert_eq!(q["category"]["criteria"]["spam"], spam);
        // The default trays and spam, each with its built-in description.
        assert_eq!(q["category"]["criteria"].as_object().unwrap().len(), 8);

        for key in [
            "personal",
            "alerts",
            "receipts",
            "newsletters",
            "promotional",
        ] {
            assert_eq!(q["category"]["criteria"][key], builtin(key), "{key}");
        }

        // `updates` is no default but keeps jevmail's text for old configs.
        assert_eq!(builtin("updates"), updates);
        assert_eq!(q["urgency"]["type"], "score");
        assert_eq!(q["urgency"]["instructions"], urgency);
        assert_eq!(
            q["urgency"]["criteria"],
            json!([
                "No reply or action needed, or no time pressure at all",
                "Within a week is fine",
                "Within a few days is expected",
                "Today is expected",
                "A person is blocked, or a deadline falls within 24 hours",
            ])
        );
        assert_eq!(q["action_required"]["type"], "noul");
        assert!(q["action_required"].get("criteria").is_none());
        assert_eq!(q["is_personal"]["type"], "noul");
        assert_eq!(q["is_personal"]["instructions"], personal);
        assert!(q["is_personal"].get("criteria").is_none());
    }
}
